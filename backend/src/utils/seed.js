async function seedQuestions(Question, ExamConfig) {
  const count = await Question.count();
  if (count > 0) return; // Already seeded

  await Question.bulkCreate(questions);

  // Get all exam questions (already flagged in seed data)
  const examQuestions = await Question.findAll({
    where: { isExamQuestion: true },
    order: [['sortOrder', 'ASC']],
  });
  const ids = examQuestions.map(q => q.id);

  await ExamConfig.update(
    { selectedQuestionIds: ids },
    { where: { id: 1 } }
  );

  console.log(`Seeded ${questions.length} questions: 6 training scenarios + 20 exam questions (IDs: ${ids.join(', ')})`);
}

