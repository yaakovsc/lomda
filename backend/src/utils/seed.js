async function seedQuestions(Question, ExamConfig) {
  const count = await Question.count({ where: { trainingType: 'cyber' } });
  if (count > 0) return; // Already seeded

  await Question.bulkCreate(questions.map(q => ({ ...q, trainingType: 'cyber' })));

  // Get all exam questions (already flagged in seed data)
  const examQuestions = await Question.findAll({
    where: { isExamQuestion: true, trainingType: 'cyber' },
    order: [['sortOrder', 'ASC']],
  });
  const ids = examQuestions.map(q => q.id);

  await ExamConfig.update(
    { selectedQuestionIds: ids },
    { where: { trainingType: 'cyber' } }
  );

  console.log(`Seeded ${questions.length} cyber questions: 6 training scenarios + 20 exam questions (IDs: ${ids.join(', ')})`);
}

