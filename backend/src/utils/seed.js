async function seedHarasSlides(TrainingSlide) {
  const count = await TrainingSlide.count({ where: { trainingType: 'haras' } });
  if (count > 0) return;
  const slidesWithIds = harasSlideSeedData.map((s, i) => ({ ...s, id: 101 + i }));
  await TrainingSlide.bulkCreate(slidesWithIds);
  console.log(`Seeded ${harasSlideSeedData.length} harassment training slides`);
}

async function seedHarasQuestions(Question, ExamConfig) {
  const count = await Question.count({ where: { trainingType: 'haras' } });
  if (count > 0) return;

  await Question.bulkCreate(harasQuestions);

  const examQuestions = await Question.findAll({
    where: { isExamQuestion: true, trainingType: 'haras' },
    order: [['sortOrder', 'ASC']],
  });
  const ids = examQuestions.map(q => q.id);

  await ExamConfig.update(
    { selectedQuestionIds: ids },
    { where: { trainingType: 'haras' } }
  );

  console.log(`Seeded ${harasQuestions.length} harassment questions: 6 scenarios + 20 exam questions (IDs: ${ids.join(', ')})`);
}

