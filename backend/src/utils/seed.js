async function seedSafetySlides(TrainingSlide) {
  const count = await TrainingSlide.count({ where: { trainingType: 'safety' } });
  if (count > 0) return;
  const slidesWithIds = safetySlideSeedData.map((s, i) => ({ ...s, id: 201 + i }));
  await TrainingSlide.bulkCreate(slidesWithIds);
  console.log(`Seeded ${safetySlideSeedData.length} safety training slides`);
}

async function seedSafetyQuestions(Question, ExamConfig) {
  const count = await Question.count({ where: { trainingType: 'safety' } });
  if (count > 0) return;

  await Question.bulkCreate(safetyQuestions);

  const examQuestions = await Question.findAll({
    where: { isExamQuestion: true, trainingType: 'safety' },
    order: [['sortOrder', 'ASC']],
  });
  const ids = examQuestions.map(q => q.id);

  await ExamConfig.update(
    { selectedQuestionIds: ids },
    { where: { trainingType: 'safety' } }
  );

  console.log(`Seeded ${safetyQuestions.length} safety questions: 6 scenarios + 20 exam questions (IDs: ${ids.join(', ')})`);
}

